<#
.SYNOPSIS
    注册 Chrome Postman 的 Native Messaging 伴生程序（Windows）。

.DESCRIPTION
    这个脚本做四件事：
      1. 把 bridge.mjs 和 host manifest 复制到 %LOCALAPPDATA%\ChromePostman
      2. 生成一个 bridge.cmd 启动包装器
         【为什么需要它】Chrome 在 Windows 上只会启动 .exe / .bat / .cmd，
         不会直接执行 .mjs（.mjs 不是 Windows 可执行文件，也没有 shebang 机制）。
      3. 把 manifest 里的 allowed_origins 换成你真实的扩展 ID
         【为什么必须精确到扩展 ID】Chrome 不允许通配符，写错了扩展连不上伴生程序。
      4. 写注册表项 HKCU\Software\Google\Chrome\NativeMessagingHosts\com.chrome_postman.bridge
         【为什么写 HKCU（当前用户）】不需要管理员权限，普通用户自己就能装。

.PARAMETER ExtensionId
    Chrome 扩展 ID（32 位，字符范围 a-p）。在 chrome://extensions 页面上可以看到。

.PARAMETER InstallDir
    安装目录，默认 %LOCALAPPDATA%\ChromePostman。

.PARAMETER Browser
    装给哪个 Chromium 内核浏览器：Chrome / Chromium / Edge。

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File .\install-host.ps1 -ExtensionId abcdefghijklmnopabcdefghijklmnop

.NOTES
    装完必须完全退出并重启 Chrome：Chrome 在启动时读取注册表，
    运行中改注册表不会立刻生效。
#>
[CmdletBinding()]
param(
    [string]$ExtensionId,

    [string]$InstallDir = (Join-Path $env:LOCALAPPDATA 'ChromePostman'),

    [ValidateSet('Chrome', 'Chromium', 'Edge')]
    [string]$Browser = 'Chrome'
)

$ErrorActionPreference = 'Stop'

$HostName = 'com.chrome_postman.bridge'
$ScriptDir = $PSScriptRoot

# ---------------------------------------------------------------------------
# 1. 校验扩展 ID
# ---------------------------------------------------------------------------

if ([string]::IsNullOrWhiteSpace($ExtensionId)) {
    Write-Host ''
    Write-Host '✗ 缺少 -ExtensionId 参数。' -ForegroundColor Red
    Write-Host ''
    Write-Host '  Chrome 不允许在 allowed_origins 里使用通配符，必须写死你的扩展 ID。' -ForegroundColor Yellow
    Write-Host '  拿 ID 的方法：'
    Write-Host '    1. 浏览器打开 chrome://extensions'
    Write-Host '    2. 找到 "Chrome Postman"，打开「开发者模式」'
    Write-Host '    3. 复制卡片上的「ID」（32 位，a-p 开头的那种）'
    Write-Host ''
    Write-Host '  然后这样运行：' -ForegroundColor Cyan
    Write-Host '    powershell -NoProfile -ExecutionPolicy Bypass -File .\install-host.ps1 -ExtensionId <你的ID>' -ForegroundColor Cyan
    Write-Host ''
    exit 1
}

# Chrome 扩展 ID 固定是 32 个 a-p 字符。写错了 Chrome 会直接拒绝连接，所以这里先拦一道。
if ($ExtensionId -notmatch '^[a-p]{32}$') {
    Write-Host "✗ 扩展 ID 格式不对：'$ExtensionId'" -ForegroundColor Red
    Write-Host '  扩展 ID 必须是 32 个字符，且只能包含 a-p（例如 abcdefghijklmnopabcdefghijklmnop）。' -ForegroundColor Yellow
    Write-Host '  请到 chrome://extensions 复制，不要复制扩展名称或路径。' -ForegroundColor Yellow
    exit 1
}

# ---------------------------------------------------------------------------
# 2. 检查源文件
# ---------------------------------------------------------------------------

$bridgeSrc = Join-Path $ScriptDir 'bridge.mjs'
$manifestSrc = Join-Path $ScriptDir 'com.chrome_postman.bridge.json'

foreach ($f in @($bridgeSrc, $manifestSrc)) {
    if (-not (Test-Path -LiteralPath $f)) {
        Write-Host "✗ 找不到文件：$f" -ForegroundColor Red
        Write-Host '  请在 native-host/ 目录下运行这个脚本。' -ForegroundColor Yellow
        exit 1
    }
}

# ---------------------------------------------------------------------------
# 3. 检查 Node.js
# ---------------------------------------------------------------------------

$nodeCommand = Get-Command node -ErrorAction SilentlyContinue
if ($null -eq $nodeCommand) {
    Write-Host '✗ 找不到 node 命令。' -ForegroundColor Red
    Write-Host '  伴生程序需要 Node.js 18 以上版本，请先到 https://nodejs.org 安装。' -ForegroundColor Yellow
    exit 1
}
$nodeExe = $nodeCommand.Source
Write-Host "✓ 找到 Node.js：$nodeExe" -ForegroundColor Green

# ---------------------------------------------------------------------------
# 4. 复制文件
# ---------------------------------------------------------------------------

if (-not (Test-Path -LiteralPath $InstallDir)) {
    New-Item -ItemType Directory -Path $InstallDir -Force | Out-Null
}
Write-Host "✓ 安装目录：$InstallDir" -ForegroundColor Green

$bridgeDst = Join-Path $InstallDir 'bridge.mjs'
$manifestDst = Join-Path $InstallDir "$HostName.json"
$cmdDst = Join-Path $InstallDir 'bridge.cmd'

Copy-Item -LiteralPath $bridgeSrc -Destination $bridgeDst -Force
Copy-Item -LiteralPath $manifestSrc -Destination $manifestDst -Force
Write-Host '✓ 已复制 bridge.mjs 与 host manifest' -ForegroundColor Green

# ---------------------------------------------------------------------------
# 5. 生成 bridge.cmd 包装器
# ---------------------------------------------------------------------------
#
# 【为什么写死 node.exe 的绝对路径】
#   Chrome 启动伴生程序时传下来的环境变量不一定完整，
#   只靠 PATH 里的 node 有找不到的风险，所以安装时把真实路径写进去。
#
# 【为什么 .cmd 里的注释用英文】
#   这个文件是交给 cmd.exe 执行的，cmd 用系统 OEM 代码页读文件，
#   中文注释会变成乱码。说明文字放在 install-host.ps1 和 README 里。
$cmdContent = @(
    '@echo off',
    'rem Generated by install-host.ps1 - do not edit by hand.',
    'rem Chrome on Windows cannot execute .mjs directly; this wrapper hands off to node.exe.',
    "`"$nodeExe`" `"%~dp0bridge.mjs`" %*"
)
# 用 ASCII 写入，避免 cmd.exe 读到 UTF-8 BOM 时的乱码
Set-Content -LiteralPath $cmdDst -Value $cmdContent -Encoding ASCII
Write-Host '✓ 已生成启动包装器 bridge.cmd' -ForegroundColor Green

# ---------------------------------------------------------------------------
# 6. 改写 manifest（填扩展 ID + 指向 bridge.cmd）
# ---------------------------------------------------------------------------

# 【坑：必须显式指定 UTF-8】
#   源 manifest 是无 BOM 的 UTF-8 文件，而 Windows PowerShell 5.1 的
#   Get-Content 在没有 BOM 时会按系统 ANSI 代码页（中文机器上是 GBK）去解码，
#   结果 description 里的中文会变成乱码，还会被原样写回安装目录。
#   所以这里绕开 Get-Content，直接用 .NET API 按 UTF-8 读。
$manifestJson = [System.IO.File]::ReadAllText($manifestSrc, (New-Object System.Text.UTF8Encoding($false)))
$manifest = $manifestJson | ConvertFrom-Json
$manifest.allowed_origins = @("chrome-extension://$ExtensionId/")
$manifest.path = $cmdDst

$json = $manifest | ConvertTo-Json -Depth 5
# 用 .NET API 写文件：明确用 UTF-8 且不带 BOM，JSON 解析器最省心
[System.IO.File]::WriteAllText($manifestDst, $json, (New-Object System.Text.UTF8Encoding($false)))

Write-Host "✓ 已写入 allowed_origins：chrome-extension://$ExtensionId/" -ForegroundColor Green

# ---------------------------------------------------------------------------
# 7. 写注册表
# ---------------------------------------------------------------------------

$regRoots = @{
    'Chrome'   = 'HKCU:\Software\Google\Chrome\NativeMessagingHosts'
    'Chromium' = 'HKCU:\Software\Chromium\NativeMessagingHosts'
    'Edge'     = 'HKCU:\Software\Microsoft\Edge\NativeMessagingHosts'
}
$regPath = Join-Path $regRoots[$Browser] $HostName

New-Item -Path $regPath -Force | Out-Null
Set-Item -Path $regPath -Value $manifestDst

Write-Host "✓ 已注册（$Browser）：$regPath" -ForegroundColor Green
Write-Host "    → $manifestDst" -ForegroundColor DarkGray

# ---------------------------------------------------------------------------
# 8. 收尾提示
# ---------------------------------------------------------------------------

Write-Host ''
Write-Host '安装完成！接下来：' -ForegroundColor Cyan
Write-Host '  1. 完全退出 Chrome（关掉所有窗口，不只是关标签页）'
Write-Host '  2. 重新打开 Chrome'
Write-Host '  3. 在扩展里打开「跳过证书校验」开关，它会显示「本地桥接 v1.0.0 已就绪」'
Write-Host ''
Write-Host '排查：' -ForegroundColor DarkGray
Write-Host "  查注册表：reg query `"$regPath`"" -ForegroundColor DarkGray
Write-Host "  手动握手：`"$nodeExe`" `"$bridgeDst`" < NUL" -ForegroundColor DarkGray
Write-Host ''
